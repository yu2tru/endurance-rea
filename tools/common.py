def ph(text):
    """Visible, clearly marked placeholder for facts the old site does not contain."""
    return f'<mark class="ph">[{esc(text)}]</mark>'


def img(name, alt, sizes='100vw', eager=False, cls='', focal=None):
    """Responsive WebP <img> with width/height. focal = CSS object-position."""
    ws = IMG[name]['sizes']
    srcset = ', '.join(f'/images/{name}-{w}.webp {w}w' for w, h in ws)
    w, h = ws[-1]
    mid = ws[1] if len(ws) > 1 else ws[0]
    attrs = 'fetchpriority="high" decoding="async"' if eager else 'loading="lazy" decoding="async"'
    c = f' class="{cls}"' if cls else ''
    if isinstance(focal, tuple):  # (desktop, mobile) focal points for heroes
        st = f' style="--fp:{focal[0]};--fpm:{focal[1]}"'
    else:
        st = f' style="object-position:{focal}"' if focal else ''
    return (f'<img src="/images/{name}-{mid[0]}.webp" srcset="{srcset}" sizes="{sizes}" '
            f'width="{w}" height="{h}" alt="{esc(alt)}" {attrs}{c}{st}>')


